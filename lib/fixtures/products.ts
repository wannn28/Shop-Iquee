function oxfordVariations(): Variation[] {
  const variations: Variation[] = [];
  for (const color of ["Stone", "Ink"]) {
    for (const size of ["S", "M", "L", "XL"]) {
      const out = color === "Ink" && size === "S";
      variations.push({
        id: `1005-${color.toLowerCase()}-${size.toLowerCase()}`,
        attributes: { Color: color, Size: size },
        price: "98.00",
        regularPrice: "98.00",
        salePrice: null,
        stockStatus: out ? "outofstock" : "instock",
        stockQuantity: out ? 0 : 8,
      });
    }
  }
  return variations;
}

